import type { OrderStatus } from '../state/order-state';

/**
 * # The order event bus — the CONTRACT between modules
 *
 * This file is the public surface that Inventory (06), CRM (08) and
 * Notification (10) code against. A subscriber should need to import the types
 * and the name constants from here and nothing else from `OrderModule` —
 * never `OrderService`, never the repository, never a state class.
 *
 * Bus: NestJS `EventEmitter2` (registered globally via `EventEmitterModule`).
 *
 * ## Events fire AFTER the transaction commits
 *
 * `OrderService` runs inside a request transaction that is committed by
 * `TenantContextMiddleware` on `res.finish` — after the handler returns. So
 * events are registered with `connection.onCommit(...)` and published only once
 * the COMMIT has succeeded. Two consequences a subscriber can rely on:
 *
 *   - the order row is already durable and visible to OTHER connections, so a
 *     handler may freely query it (this is the whole point: a subscriber that
 *     re-read the order on its own connection would otherwise see zero rows);
 *   - a request that rolls back publishes NOTHING, so no subscriber ever hears
 *     about an order that was never written.
 *
 * Handlers must NOT assume the request transaction is still open — it is closed
 * by the time they run — and should do their own work on their own
 * connection/facility (queue, cache) rather than reaching for a finished
 * transaction.
 *
 * ## Known limit: in-process, best-effort
 *
 * Delivery is in-process via `EventEmitter2`, so a subscriber that must not be
 * missed (stock deduction, a customer notification) should still be idempotent
 * and should not assume at-least-once delivery across a process crash. The
 * upgrade path, if the bus ever needs durability, is a transactional outbox
 * written in the same transaction and drained by a separate worker — deliberately
 * NOT built here, since nothing requires it yet.
 *
 * Every payload carries `tenantId` even though subscribers often only need
 * `branchId`: a cross-tenant mix-up in a multi-tenant SaaS is a data breach,
 * and one discriminator on the payload makes such a bug impossible to write
 * by accident.
 */

/** The three event names published by `OrderModule`. */
export const ORDER_EVENTS = {
  /** A brand new order row was created. Fired exactly once per order. */
  placed: 'order.placed',
  /** Any successful status transition. Also fired for the initial placement. */
  statusChanged: 'order.status_changed',
  /** The order reached `paid`. A narrowing of `status_changed`, for convenience. */
  paid: 'order.paid',
} as const;

export type OrderEventName = (typeof ORDER_EVENTS)[keyof typeof ORDER_EVENTS];

interface OrderEventBase {
  /** Discriminator matching the emitted event name, for narrow switches. */
  readonly event: string;
  readonly orderId: string;
  readonly tenantId: string;
  /** The KDS axis — the room a Kitchen Display subscribes to. */
  readonly branchId: string;
  /** ISO-8601, stamped once by the publisher and copied to every payload. */
  readonly occurredAt: string;
}

/**
 * `order.placed` — a new order exists.
 *
 * Inventory deducts recipe ingredients on this; Notification can acknowledge to
 * the guest; CRM can attach the customer to a visit.
 *
 * `previousStatus` is intentionally absent: there is no prior state, and
 * `order.status_changed` is emitted alongside this with `previousStatus:
 * null` for subscribers that only care about one stream.
 */
export interface OrderPlacedEvent extends OrderEventBase {
  readonly event: typeof ORDER_EVENTS.placed;
  readonly orderType: OrderType;
  /** Always `'placed'` — an order is created into the first state. */
  readonly status: 'placed';
  /** Dine-in orders carry this; it is what the table side-effect keys on. */
  readonly tableId: string | null;
  readonly customerId: string | null;
  readonly totalAmount: number;
  /** Lines, for subscribers that need to price/deduct without re-reading. */
  readonly items: readonly OrderPlacedItem[];
}

/**
 * A priced line as it was sold.
 *
 * There is no `orderItemId` here: the line ids are generated by the INSERT, and
 * re-reading them purely to fill in an event field would mean a second query on
 * the hot path. A subscriber that needs the persisted row (Inventory) has the
 * `orderId` and can fetch it.
 */
export interface OrderPlacedItem {
  readonly menuItemId: string;
  readonly quantity: number;
  /** Base price captured at order time, BEFORE modifier extras. */
  readonly unitPrice: number;
  readonly notes: string | null;
}

/** `order.status_changed` — the order moved between statuses. */
export interface OrderStatusChangedEvent extends OrderEventBase {
  readonly event: typeof ORDER_EVENTS.statusChanged;
  /** `null` only for the placement event, where there was no prior state. */
  readonly previousStatus: OrderStatus | null;
  readonly newStatus: OrderStatus;
  /** Present for dine-in orders; the table whose status may have changed. */
  readonly tableId: string | null;
  readonly orderType: OrderType;
  readonly totalAmount: number;
}

/**
 * `order.paid` — settlement confirmed by the payment provider.
 *
 * Fired in ADDITION to `order.status_changed` (with
 * `previousStatus: 'awaiting_payment'`), never instead of it: subscribers that
 * drive fulfilment continue to use `status_changed`, and money-shaped
 * consumers use this so they are not coupled to the exact status the order
 * happened to be in when the webhook landed.
 */
export interface OrderPaidEvent extends OrderEventBase {
  readonly event: typeof ORDER_EVENTS.paid;
  readonly previousStatus: OrderStatus;
  readonly tableId: string | null;
  readonly totalAmount: number;
}

export const ORDER_TYPES = ['dine_in', 'takeaway', 'delivery'] as const;
export type OrderType = (typeof ORDER_TYPES)[number];

export function isOrderType(value: unknown): value is OrderType {
  return (
    typeof value === 'string' &&
    (ORDER_TYPES as readonly string[]).includes(value)
  );
}
